# Калькулятор скидки. Спросить у пользователя цену товара. Спросить процент скидки. Посчитать и вывести цену со скидкой. - файл discount.py

total_sum = int(input("Введите стоимость товара: "))
discount = int(input("Введите размер скидки: "))
with_discount = total_sum * (1 - discount / 100)
print(f"Стоимость с учетом скидки составит: {with_discount}")